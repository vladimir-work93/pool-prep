"""
Угадай число наоборот. Вы загадываете число от 1 до 100, компьютер
угадывает его с помощью бинарного поиска за минимальное число попыток.
В конце выводит, за сколько попыток угадал. Готово: вы понимаете и можете
объяснить, почему всегда не больше 7 попыток.
"""

low = 1
high = 100
attempts = 0

while True:
    guess = (high + low) // 2
    attempts += 1

    user_answer = input(f"Компьютер думает, что это число {guess}. Он угадал? Выбери:\n"
          f"'y' - да\n"
          f"'+' - нет, число больше\n"
          f"'-' - нет, число меньше\n")
    if user_answer == 'y':
        print(f"Ура! Игра окончена!")
        break
    elif user_answer == '+':
        low = guess + 1
        print(f"Компьютер принял, что загаданное число больше!")
    elif user_answer == '-':
        high = guess - 1
        print(f"Компьютер принял, что загаданное число меньше!")

print(f"Загаданное число {guess}. Попыток: {attempts}")